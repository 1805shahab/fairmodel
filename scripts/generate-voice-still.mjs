// Original decorative artwork, generated offline rather than during hydration.
// Run from any directory: node scripts/generate-voice-still.mjs
import { mkdirSync, writeFileSync } from "node:fs";

const curves = Array.from({ length: 26 }, (_, i) => {
  const points = Array.from({ length: 180 }, (_, j) => {
    const a = (j / 179) * Math.PI * 2;
    const r = 112 + (i - 13) * 2.5 + 18 * Math.cos(3 * a + i * 0.05);
    const x = 250 + Math.sin(a) * r;
    const y = 210 + Math.cos(a) * r * 0.94 + 34 * Math.sin(3 * a + i * 0.04);
    return `${x.toFixed(3)},${y.toFixed(3)}`;
  }).join(" ");
  return `  <polyline points="${points}" opacity="${(0.35 + i / 50).toFixed(2)}"/>`;
}).join("\n");

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 500 420" width="500" height="420">
  <!-- Original FairModel illustration. Generated by scripts/generate-voice-still.mjs. -->
  <defs><linearGradient id="voice-silver"><stop stop-color="#8be2ff"/><stop offset=".45" stop-color="#f8f4ed"/><stop offset="1" stop-color="#7396b6"/></linearGradient></defs>
  <g fill="none" stroke="url(#voice-silver)" stroke-width="1.15">
${curves}
  </g>
</svg>
`;
mkdirSync(new URL("../frontend/public/", import.meta.url), { recursive: true });
writeFileSync(
  new URL("../frontend/public/voice-sculpture-still.svg", import.meta.url),
  svg,
);
